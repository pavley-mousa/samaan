create policy "Users read own profile or admins read all" on public.profiles for select to authenticated using (id = auth.uid() or public.is_admin());
create policy "Users update own profile or admins update all" on public.profiles for update to authenticated using (id = auth.uid() or public.is_admin()) with check (id = auth.uid() or public.is_admin());
create policy "Authenticated users read active categories" on public.categories for select to authenticated using (is_active or public.is_admin());
create policy "Admins manage categories" on public.categories for all to authenticated using (public.is_admin()) with check (public.is_admin());
create policy "Authenticated users read active products" on public.products for select to authenticated using (is_active or public.is_admin());
create policy "Admins manage products" on public.products for all to authenticated using (public.is_admin()) with check (public.is_admin());
create policy "Authenticated users read active variants" on public.product_variants for select to authenticated using (is_active or public.is_admin());
create policy "Admins manage variants" on public.product_variants for all to authenticated using (public.is_admin()) with check (public.is_admin());
create policy "Authenticated users read product images" on public.product_images for select to authenticated using (exists(select 1 from public.products p where p.id = product_id and p.is_active) or public.is_admin());
create policy "Admins manage product images" on public.product_images for all to authenticated using (public.is_admin()) with check (public.is_admin());
create policy "Authenticated users read wholesale tiers" on public.wholesale_price_tiers for select to authenticated using (true);
create policy "Admins manage wholesale tiers" on public.wholesale_price_tiers for all to authenticated using (public.is_admin()) with check (public.is_admin());
create policy "Users manage own addresses" on public.addresses for all to authenticated using (user_id = auth.uid() or public.is_admin()) with check (user_id = auth.uid() or public.is_admin());
create policy "Users read own orders or admins read all" on public.orders for select to authenticated using (user_id = auth.uid() or public.is_admin());
create policy "Users create own orders" on public.orders for insert to authenticated with check (user_id = auth.uid());
create policy "Admins update orders" on public.orders for update to authenticated using (public.is_admin()) with check (public.is_admin());
create policy "Users read own order items or admins read all" on public.order_items for select to authenticated using (exists(select 1 from public.orders o where o.id = order_id and (o.user_id = auth.uid() or public.is_admin())));
create policy "Users create items for own orders" on public.order_items for insert to authenticated with check (exists(select 1 from public.orders o where o.id = order_id and o.user_id = auth.uid()));
create policy "Admins manage order items" on public.order_items for all to authenticated using (public.is_admin()) with check (public.is_admin());
create policy "Users manage own tailoring requests" on public.tailoring_requests for all to authenticated using (user_id = auth.uid() or public.is_admin()) with check (user_id = auth.uid() or public.is_admin());
create policy "Users manage own favorites" on public.favorites for all to authenticated using (user_id = auth.uid() or public.is_admin()) with check (user_id = auth.uid() or public.is_admin());

